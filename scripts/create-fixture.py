from pathlib import Path
import tempfile

base = Path(tempfile.mkdtemp(prefix="qqnt-MOCK-DATA-"))
root = base / "Tencent Files" / "模拟账号_10001" / "nt_qq" / "nt_data"
for name in ("Pic", "Video", "nt_db", "File", "Emoji"):
    (root / name).mkdir(parents=True)
media = Path(__file__).resolve().parent.parent / 'tests' / 'fixtures' / 'media'
files = {
    "Pic/模拟图片.png": (media / "image.png").read_bytes(),
    "Pic/损坏的图片.jpg": b"deliberately corrupt fixture",
    "Video/模拟可播放.mp4": (media / "video.mp4").read_bytes(),
    "nt_db/chat.db": b"SQLite format 3\x00MOCK DATABASE - NOT REAL QQ DATA",
    "File/重要接收文件.txt": "模拟数据：接收文件必须保护。".encode(),
    "Emoji/unknown.dat": bytes(128),
    "MOCK_DATA.txt": b"SIMULATED DATA ONLY - generated by create-fixture.py",
}
for relative, contents in files.items():
    (root / relative).write_bytes(contents)
expected = {"simulated": True, "root": str(root), "files": len(files), "bytes": sum(map(len, files.values()))}
(base / "expected.json").write_text(json.dumps(expected, ensure_ascii=False, indent=2), encoding="utf-8")
print(json.dumps(expected, ensure_ascii=False, indent=2))
